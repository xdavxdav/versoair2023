export type TranslationDictionary = Record<string, string>;

export function normalizePublicCopy(text: string): string {
  return text.replace(/\s+/g, " ").trim();
}

const sourceIds = new Map<string, string>();
PUBLIC_COPY.forEach(([en, fr], index) => {
  sourceIds.set(normalizePublicCopy(en), String(index));
  sourceIds.set(normalizePublicCopy(fr), String(index));
});

export function getPublicCopyId(text: string): string | undefined {
  return sourceIds.get(normalizePublicCopy(text));
}

export function nativeDictionary(lang: "fr" | "en"): TranslationDictionary {
  return Object.fromEntries(
    PUBLIC_COPY.map((pair, index) => [String(index), pair[lang === "fr" ? 1 : 0]]),
  );
}
